let num1 = 1;
let num2 = 2;
function usarNumeros(num1, num2) {
    if (num1 > num2) {
        console.log(`O número ${num1} é maior que o ${num2}`);
    }
    else if (num2 > num1) {
        console.log(`O número ${num2} é maior que o ${num1}`);
    }
    else {
        console.log('Os números são iguais')
    }
}
usarNumeros(num1, num2);



